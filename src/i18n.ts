export type TranslationKey = keyof (typeof translations)["en"];

export type TranslationValues = Record<string, string | number>;

export type TranslateFn = (
  key: TranslationKey,
  values?: TranslationValues,
) => string;

export const localeOptions: Locale[] = ["en", "zh-CN"];

export function getPreferredLocale(): Locale {
  if (typeof navigator === "undefined") {
    return "en";
  }

  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function createTranslator(locale: Locale): TranslateFn {
  return (key, values) => {
    const template = String(translations[locale][key] ?? translations.en[key]);

    if (!values) {
      return template;
    }

    return Object.entries(values).reduce((message, [token, value]) => {
      return message.split(`{${token}}`).join(String(value));
    }, template);
  };
}
